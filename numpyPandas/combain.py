"""
Лекция 4. DataFrame как обобщённый массив NumPy
------------------------------------------------
Код к слайдам: подготовка примера, .shape, .ndim, .values,
DataFrame как словарь объектов Series, создание DataFrame из массива NumPy.

Запуск:  python lecture_04_dataframe_numpy.py
Нужно:   pip install pandas numpy
"""

import numpy as np
import pandas as pd


def line(title):
    print("\n" + "=" * 60)
    print(title)
    print("=" * 60)


# ---------------------------------------------------------------
# Слайд 5. Подготовка: создаём пример DataFrame
# Таблица: три города, температура и влажность
# ---------------------------------------------------------------
line("Слайд 5. Пример DataFrame")

data = {
    "Город": ["Бишкек", "Ош", "Каракол"],
    "Температура": [28, 34, 19],
    "Влажность": [35, 28, 61],
}

df = pd.DataFrame(data)
df = df.set_index("Город")   # метки строк — названия городов
print(df)


# ---------------------------------------------------------------
# Слайд 6. Атрибут .shape — размерность (строки, столбцы)
# ---------------------------------------------------------------
line("Слайд 6. .shape")

print("df.shape      ->", df.shape)          # (3, 2)
print("строк:        ->", df.shape[0])
print("столбцов:     ->", df.shape[1])

# Для сравнения — один столбец (Series)
print("df['Температура'].shape ->", df["Температура"].shape)   # (3,)


# ---------------------------------------------------------------
# Слайд 7. Атрибут .ndim — количество измерений
# У DataFrame всегда 2, у Series — 1
# ---------------------------------------------------------------
line("Слайд 7. .ndim")

print("df.ndim                 ->", df.ndim)                   # 2
print("df['Влажность'].ndim    ->", df["Влажность"].ndim)      # 1
print("тип столбца             ->", type(df["Влажность"]))     # pandas Series


# ---------------------------------------------------------------
# Слайд 8. Атрибут .values — «чистый» массив NumPy
# Индексы и названия столбцов отбрасываются
# ---------------------------------------------------------------
line("Слайд 8. .values")

arr = df.values
print(arr)
print("тип        ->", type(arr))        # numpy.ndarray
print("dtype      ->", arr.dtype)
print("shape      ->", arr.shape)

# Важно: если в таблице есть и числа, и строки, NumPy приведёт всё к object
mixed = pd.DataFrame({"a": [1, 2], "b": ["x", "y"]})
print("\nСмешанные типы -> dtype:", mixed.values.dtype)


# ---------------------------------------------------------------
# Слайд 4. Две точки зрения на DataFrame
# 1) как двумерный массив  2) как словарь из Series
# ---------------------------------------------------------------
line("Слайд 4. Две точки зрения")

# 1) Как массив: работают векторизованные операции
print("Температура в Фаренгейтах:")
print(df["Температура"] * 9 / 5 + 32)

print("\nСреднее по каждому столбцу:")
print(df.mean())

# 2) Как словарь: ключ — имя столбца, значение — Series
print("\nКлючи (столбцы):", list(df.keys()))
for name in df.columns:
    column = df[name]
    print(f"  {name}: Series, ndim={column.ndim}, значения={column.tolist()}")


# ---------------------------------------------------------------
# Слайд 9. Пример 1. Создание DataFrame на основе массива NumPy
# ---------------------------------------------------------------
line("Слайд 9. Из массива NumPy в DataFrame")

np.random.seed(42)                      # чтобы результат повторялся
raw = np.random.randint(0, 100, size=(3, 3))
print("Массив NumPy:")
print(raw)

table = pd.DataFrame(
    raw,
    index=["Город_А", "Город_Б", "Город_В"],
    columns=["Температура", "Влажность", "Давление"],
)

print("\nDataFrame:")
print(table)

# Обратный путь: DataFrame -> NumPy
print("\nОбратно в NumPy (.to_numpy()):")
print(table.to_numpy())


# ---------------------------------------------------------------
# Сравнительная сводка (можно показать в конце лекции)
# ---------------------------------------------------------------
line("NumPy ndarray vs Pandas DataFrame")

print(f"{'':22}{'ndarray':<18}{'DataFrame'}")
print(f"{'Типы данных':22}{'одинаковые':<18}{'разные по столбцам'}")
print(f"{'Индексы':22}{'только числа':<18}{'любые метки'}")
print(f"{'Размерность':22}{'1..N':<18}{'всегда 2'}")
col = "df['имя']"
print(f"{'Доступ к столбцу':22}{'arr[:, 0]':<18}{col}")